        /// <summary>
        /// 测量"每个引用类型对象"在托管堆上占多少字节（做法来自 InternalsLab 的 E04）。
        /// ★ 原理：先强制 GC 得到干净基线 → 分配 count 个对象 → 看堆长大了多少 → 平均。
        /// ★ 用法（TODO 2、TODO 3 都要用）：
        ///     long size = MeasureClass&lt;OneInt&gt;();
        /// </summary>
        // ★ NoInlining = 禁止 JIT 把这个方法内联进调用方。
        //   测量内存的方法一旦内联，局部变量就和调用方混在一起，量的东西就不干净了。
        [MethodImpl(MethodImplOptions.NoInlining)]
        static long MeasureClass<T>(int count = 100_000) where T : new()
        {
            // ① 先回收两轮，把前面产生的垃圾清干净，before 才是干净的起点。
            //   中间那句 WaitForPendingFinalizers 是等"终结器队列"跑完 ——
            //   有些对象要等终结器执行完才真正被回收，不等它，垃圾会被算进结果里。
            GC.Collect();
            GC.WaitForPendingFinalizers();
            GC.Collect();

            // ② GetTotalMemory(true)：先做一次完整回收，再返回"当前托管堆里活着的字节数"
            long before = GC.GetTotalMemory(true);

            // ③ 先造数组：一来被测量的对象得有地方挂住（否则会被 GC 收走），
            //    二来数组自身的开销待会儿要减掉
            T[] arr = new T[count];
            for (int i = 0; i < count; i++)
            {
                arr[i] = new T();       // ← 真正被测量的分配就发生在这一行
            }

            long after = GC.GetTotalMemory(true);

            // ④ ★ KeepAlive 必须写在测量【之后】：它告诉 JIT"arr 到这里还要用"，
            //    JIT 的存活分析是从后往前看的 → arr 在两次读数之间一直活着 →
            //    它挂着的 count 个对象一个都不会被回收。
            GC.KeepAlive(arr);

            // ⑤ 减掉引用数组自身的开销：24 字节头（对象头 8 + MethodTable 指针 8 + 长度 4 + 填充 4）
            //    + 每个元素 8 字节的引用槽（x64 上一个地址就是 8 字节）
            //    ★ 先转 double 再除！写成 / count 的话，24 会被截断成 23（第 11 课踩过这个坑）。
            double perObject = (after - before - (24 + count * 8L)) / (double)count;
            return (long)Math.Round(perObject);
        }

        /// <summary>
        /// 测量"struct 数组里每个元素"占多少字节。
        /// ★ 元素是【内嵌】在数组对象内部的，所以减掉数组头之后，剩下的就是"数据本身"，
        ///   里面【不含】任何 16 字节对象头 —— 这正是 struct 和 class 的关键差别。
        /// </summary>
        [MethodImpl(MethodImplOptions.NoInlining)]
        static double MeasureStruct<T>(int count = 200_000) where T : new()
        {
            GC.Collect();
            GC.WaitForPendingFinalizers();
            GC.Collect();

            long before = GC.GetTotalMemory(true);
            T[] arr = new T[count];
            for (int i = 0; i < count; i++)
            {
                arr[i] = new T();       // struct 的 new 不上堆：只是把这块内存清零
            }
            long after = GC.GetTotalMemory(true);
            GC.KeepAlive(arr);

            // ★ 元素是值类型：数组内部直接排着 count 份数据，没有"每个元素 8 字节引用槽"这回事
            return (after - before - 24) / (double)count;
        }




