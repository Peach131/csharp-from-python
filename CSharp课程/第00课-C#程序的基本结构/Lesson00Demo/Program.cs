// 【第 1 块】using —— 引用命名空间
// using 的意思是"我下面要用到这个命名空间里的东西"。
// System 是 .NET 最基础的命名空间，Console 就在里面。
//
// ★ 注意：这个项目的 .csproj 里开了 <ImplicitUsings>enable</ImplicitUsings>，
//   编译器会自动帮你补上 using System; 等常用命名空间，
//   所以这一行写不写都能跑。但写出来能让你看清楚"Console 是从哪来的"。
using System;


// 【第 2 块】namespace —— 给代码分组的"文件夹"
// 作用是避免重名冲突：你的 ConsoleHelper 和别人的 ConsoleHelper 可以共存。
// ★ 注意：namespace 名字后面【没有】分号。
namespace Lesson00Demo
{

    // 【第 3 块】class —— 装代码的盒子
    // ★ C# 的硬性规定：所有代码都必须写在某个 class 里面。
    //   不能像 Python 那样在文件顶层直接写语句。
    //
    // Program 是这个类的名字，惯例是首字母大写。
    class Program
    {

        // 【第 4 块】Main 方法 —— 程序的入口
        //
        //   static —— 静态的：表示"不用创建对象就能调用"。（第 5 课讲，先照抄）
        //   void   —— 空的  ：表示"这个方法不返回任何值"。
        //   Main   —— 名字必须是 Main（大写 M），这是 C# 规定的入口。
        //   ()     —— 参数列表，空的表示不需要参数。
        //
        // ★ 程序永远从 Main 的第一行开始执行。
        static void Main()
        {

            // 【第 5 块】Console.WriteLine —— 往屏幕打印一行
            //   Console    —— .NET 自带的类，代表控制台窗口
            //   WriteLine  —— 它的方法，打印内容并【换行】
            //   ("...")    —— 括号里是要打印的文本，用英文双引号包起来
            //   ;          —— 分号表示这句结束。C# 每条语句末尾都必须有分号！
            Console.WriteLine("========== 第 00 课：C# 程序的基本结构 ==========");
            Console.WriteLine();

            // ----------------------------------------------------------------
            // 演示 1：WriteLine 和 Write 的区别
            // ----------------------------------------------------------------
            Console.WriteLine("---- 演示 1：WriteLine vs Write ----");

            // WriteLine 打印完会换行
            Console.Write("这一行用 Write 打印，");
            Console.Write("所以它们在同一行。");
            Console.WriteLine();     // 空的 WriteLine() 只做一件事：换行

            Console.WriteLine("这一行用 WriteLine 打印，所以它在下一行。");
            Console.WriteLine();


            // ----------------------------------------------------------------
            // 演示 2：变量与字符串插值
            // ----------------------------------------------------------------
            Console.WriteLine("---- 演示 2：变量与字符串插值 ----");

            // 声明一个整数变量：类型 名字 = 值;
            //   int   —— 类型，表示整数
            //   age   —— 变量名，惯例是小写开头
            //   = 25  —— 赋值
            //   ;     —— 别忘分号
            int age = 25;

            // 声明一个字符串变量
            string name = "小明";

            // 普通拼接：用 + 号连接
            Console.WriteLine("我叫" + name + "，今年" + age + "岁。");

            // 字符串插值：引号前加 $，变量用 { } 包起来
            // 这样比用 + 拼接更清晰，推荐写法
            Console.WriteLine($"我叫{name}，今年{age}岁。");

            // 插值里可以直接做运算
            Console.WriteLine($"我 10 年后是 {age + 10} 岁。");
            Console.WriteLine();


            // ----------------------------------------------------------------
            // 演示 3：注释的三种写法
            // ----------------------------------------------------------------
            Console.WriteLine("---- 演示 3：注释 ----");

            // 这是单行注释，从 // 到行尾都会被编译器忽略

            /*
               这是多行注释
               可以写好几行
               中间的内容都不会被执行
            */

            Console.WriteLine("注释不会显示在输出里，它们只是给你（和人）看的。");
            Console.WriteLine();


            // ----------------------------------------------------------------
            // 演示 4：代码块 { } 和缩进
            // ----------------------------------------------------------------
            Console.WriteLine("---- 演示 4：代码块和缩进 ----");

            // C# 靠 { } 划分代码块，不靠缩进（这一点和 Python 完全不同！）
            // 下面的 if 后面必须有 { }，缩进只是为了好看
            bool isStudent = true;

            if (isStudent)
            {
                Console.WriteLine("你是学生 → 这句在 if 的 { } 里面");
            }

            // ★ 缩进不会影响程序行为，但会让代码可读。
            //   Rider 里按 Ctrl + Alt + L 可以自动整理格式。
            Console.WriteLine();


            // ----------------------------------------------------------------
            // 全部完成
            // ----------------------------------------------------------------
            Console.WriteLine("========== 示例结束 ==========");
            Console.WriteLine();
            Console.WriteLine("接下来请打开：练习\\LessonPractice\\Lesson00Practice.cs");
            Console.WriteLine("里面有 5 个 TODO 等你完成。");

            // 这一行让窗口停住，等用户按回车再关闭。
            // 不加的话，程序一跑完窗口就关了，你看不清输出。
            Console.WriteLine();
            Console.Write("按回车键退出...");
            Console.ReadLine();
        }
    }
}
